import re

# curriculum.mdを読み込む
with open('curriculum.md', 'r', encoding='utf-8') as f:
    content = f.read()

# レッスン61以降のすべてのレッスン番号を+1する
# 降順で置換することで、重複を避ける
for lesson_num in range(500, 60, -1):  # 500から61まで降順
    old_pattern = f'レッスン{lesson_num}：'
    new_pattern = f'レッスン{lesson_num + 1}：'
    content = content.replace(old_pattern, new_pattern)

# レッスン61（第6章の最初）を62に変更
content = re.sub(r'レッスン61：イベントリスナー基礎', 'レッスン62：イベントリスナー基礎', content)

# 章のレッスン範囲も更新
chapter_ranges = [
    ('第7章：繰り返しの力（レッスン73-84）', '第7章：繰り返しの力（レッスン74-85）'),
    ('第8章：配列でデータをまとめる（レッスン85-96）', '第8章：配列でデータをまとめる（レッスン86-97）'),
    ('第9章：配列とDOMの連携（レッスン97-108）', '第9章：配列とDOMの連携（レッスン98-109）'),
    ('第10章：関数で処理をまとめる（レッスン109-120）', '第10章：関数で処理をまとめる（レッスン110-121）'),
    ('第11章：関数の応用（レッスン121-132）', '第11章：関数の応用（レッスン122-133）'),
    ('第12章：オブジェクトで構造化（レッスン133-144）', '第12章：オブジェクトで構造化（レッスン134-145）'),
    ('第13章：すべてを組み合わせる（レッスン145-156）', '第13章：すべてを組み合わせる（レッスン146-157）'),
    ('第14章：総合プロジェクト（レッスン157-168）', '第14章：総合プロジェクト（レッスン158-169）'),
]

for old, new in chapter_ranges:
    content = content.replace(old, new)

# 結果を書き込む
with open('curriculum.md', 'w', encoding='utf-8') as f:
    f.write(content)

print('レッスン番号の更新が完了しました')
