// 朝の挨拶を表示する関数
function showMorning() {
  let messageDiv = document.getElementById("message");
  messageDiv.textContent = "おはようございます！";
}

// 昼の挨拶を表示する関数
function showAfternoon() {
  let messageDiv = document.getElementById("message");
  messageDiv.textContent = "こんにちは！";
}

// 夜の挨拶を表示する関数
function showEvening() {
  let messageDiv = document.getElementById("message");
  messageDiv.textContent = "こんばんは！";
}
