// subtract(a, b) - a - b を返す
// multiply(a, b) - a * b を返す
// divide(a, b) - a / b を返す（b が 0 の場合は 0 を返す）

// ========================================
// 入力取得関数
// ========================================
// getFirstNumber() - num1 の値を数値で返す
// getSecondNumber() - num2 の値を数値で返す

// ========================================
// 表示関数
// ========================================
// showResult(result) - result 要素に「結果: 」+ result を表示

// ========================================
// 履歴管理関数
// ========================================
// addToHistory(operation, num1, num2, result)
//   - 以下のオブジェクトを history 配列に追加:
//     { operation: operation, num1: num1, num2: num2, result: result, time: 現在時刻 }

// showHistory()
//   - history が空なら「まだ計算履歴がありません」を表示
//   - history に項目があれば、最新が上になるように表示
//   - 各項目は「時刻 - 数値1 演算子 数値2 = 結果」の形式

